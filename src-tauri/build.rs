include!("src/app_commands.rs");

fn main() {
    // tauri-build reads STATIC_VCRUNTIME on Windows but does not ask Cargo to
    // rerun when it changes, so a plain `cargo build` could keep stale CRT
    // link arguments from a previous `cargo tauri build`.
    println!("cargo:rerun-if-env-changed=STATIC_VCRUNTIME");
    // tauri-build prints its own rerun-if-changed lines, which turns off
    // Cargo's default "rerun when any file changes", so name these too.
    println!("cargo:rerun-if-changed=src/app_commands.rs");
    println!("cargo:rerun-if-changed=windows/app.manifest");

    // An app ACL manifest: Tauri then checks every app command against the
    // window's capabilities (capabilities/*.json), so the island window can
    // call only the two commands it uses. Without a manifest, every command
    // is callable from every local window. The generated permission files go
    // to permissions/autogenerated/ (not committed).
    let mut attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS));

    // Build scripts run on the build machine, so the target comes from
    // Cargo's environment, not from cfg!. Only the MSVC toolchain (releases,
    // CI, Windows development) is affected; the x86_64-pc-windows-gnu
    // cross-check (scripts/cross-check.sh) keeps tauri-build's defaults.
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if target_os == "windows" && target_env == "msvc" {
        // Static C runtime by default. The sherpa-onnx Windows libraries are
        // built with /MT; with the dynamic CRT the linker mixes runtimes
        // (LNK4098 on LIBCMT) and the app needs the VC++ Redistributable.
        // Tauri CLI 2.11 sets STATIC_VCRUNTIME=true for `cargo tauri
        // dev/build`, plain `cargo build` / `cargo test` do not. tauri-build
        // reads the variable from this process's environment (tauri-build
        // 2.6.3, lib.rs:708), so setting it here, before try_build, works.
        // An explicit value (e.g. "false") wins. Single-threaded here, so
        // set_var is sound; rerun-if-env-changed above looks at the outside
        // environment, which this does not change.
        if std::env::var_os("STATIC_VCRUNTIME").is_none() {
            std::env::set_var("STATIC_VCRUNTIME", "true");
        }

        // The Common Controls v6 manifest (windows/app.manifest), embedded by
        // link.exe into every binary of the package, test binaries included.
        // tauri-build would put the same manifest into the exe's resources,
        // but resources are linked into binaries only (embed-resource prints
        // rustc-link-arg-bins), so `cargo test --lib` builds a test binary
        // without it, and that binary dies at load with 0xC0000139: it
        // imports TaskDialogIndirect (tao, muda), which only comctl32 v6 has
        // (tauri-apps/tauri#13419). rustc-link-arg-tests would not help: it
        // reaches integration tests (tests/*.rs) only, not the lib's unit
        // tests. So the manifest goes through the linker for all binaries,
        // as rustc's own build.rs does for rustc.exe, and tauri-build leaves
        // it out of the resources (two RT_MANIFEST resources with ID 1 would
        // fail the link with CVT1100). link.exe also adds its default UAC
        // section (requestedExecutionLevel asInvoker).
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
            .expect("Cargo sets CARGO_MANIFEST_DIR for build scripts");
        let manifest = std::path::Path::new(&manifest_dir)
            .join("windows")
            .join("app.manifest");
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
        attributes = attributes
            .windows_attributes(tauri_build::WindowsAttributes::new_without_app_manifest());
    }

    if let Err(error) = tauri_build::try_build(attributes) {
        panic!("tauri-build failed: {error:#}");
    }
}
